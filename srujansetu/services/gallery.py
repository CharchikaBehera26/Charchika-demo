def media(kind, key=None, uploaded=None):
    """Prefer a maker's own upload, then a curated photo for known demo records."""
    if uploaded and "/static/uploads/" in str(uploaded):
        return uploaded
    if kind == "product":
        # Check direct product image mapping
        if key and key in PRODUCT_IMAGES:
            return PRODUCT_IMAGES[key]
        # Fall back to craft-based image if key matches any craft name substring
        for craft_name, craft_url in CRAFT_IMAGES.items():
            if craft_name.lower() in str(key).lower():
                return craft_url
    curated = CATALOGS.get(kind, {}).get(key) if key else None
    if curated:
        return curated
    if kind == "craft":
        return CRAFT_IMAGES.get(key, SCENE_IMAGES["crafts"])
    if uploaded:
        return uploaded
    return SCENE_IMAGES.get(key) or SCENE_IMAGES["hero"]
